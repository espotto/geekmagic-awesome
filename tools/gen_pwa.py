"""Writes src/PwaAssets.h: the web app manifest and the app icons
(tools/pwa/*.png), as flash arrays the firmware serves at /manifest.webmanifest,
/apple-touch-icon.png, /icon-192.png and /icon-512.png. Run after changing
an icon (tools/pwa_icon.py redraws them), then tools/gzip_webui.py.

Every link to them carries ?v=<hash of the content> (the manifest's icon list,
and the two <link>s in src/webui.html, which this rewrites): the device lets a
phone cache them for a week, and iOS takes a home-screen icon from its cache,
so a changed icon needs a new address. --check only reports whether the header
and the page are up to date."""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ICONS = [('apple-touch-icon.png', 'PWA_APPLE_ICON'), ('icon-192.png', 'PWA_ICON_192'), ('icon-512.png', 'PWA_ICON_512')]


def ver(data):
    return hashlib.sha256(data).hexdigest()[:8]


icons = {file: (ROOT / 'tools' / 'pwa' / file).read_bytes() for file, _ in ICONS}
manifest = {
    'name': 'GeekMagic', 'short_name': 'GeekMagic', 'id': '/', 'start_url': '/', 'scope': '/',
    'display': 'standalone', 'background_color': '#09090b', 'theme_color': '#09090b',
    'icons': [{'src': '/icon-192.png?v=' + ver(icons['icon-192.png']), 'sizes': '192x192', 'type': 'image/png'},
              {'src': '/icon-512.png?v=' + ver(icons['icon-512.png']), 'sizes': '512x512', 'type': 'image/png'}],
}


def array(name, data):
    rows = [', '.join('0x%02x' % b for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    return ('static const uint8_t %s[] PROGMEM = {\n  %s\n};\nstatic const size_t %s_LEN = %d;\n'
            % (name, ',\n  '.join(rows), name, len(data)))


out = ['// Generated by tools/gen_pwa.py from tools/pwa/*.png. Do not edit.',
       '#pragma once', '#include <Arduino.h>', '']
manifest_bytes = json.dumps(manifest, separators=(',', ':')).encode()
out.append(array('PWA_MANIFEST', manifest_bytes))
for file, name in ICONS:
    out.append(array(name, icons[file]))
header = '\n'.join(out)

page_path = ROOT / 'src' / 'webui.html'
page = page_path.read_text(encoding='utf-8')
links = (('manifest', '/manifest.webmanifest', manifest_bytes),
         ('apple-touch-icon', '/apple-touch-icon.png', icons['apple-touch-icon.png']))
for rel, path, data in links:
    page, n = re.subn(r'<link rel="%s" href="%s(\?v=[0-9a-f]*)?">' % (rel, re.escape(path)),
                      '<link rel="%s" href="%s?v=%s">' % (rel, path, ver(data)), page)
    if n != 1:
        sys.exit('webui.html: expected one <link rel="%s">' % rel)

header_path = ROOT / 'src' / 'PwaAssets.h'
if '--check' in sys.argv[1:]:
    stale = [p.name for p, text in ((header_path, header), (page_path, page))
             if p.read_text(encoding='utf-8') != text]
    if stale:
        sys.exit('out of date, run python3 tools/gen_pwa.py: ' + ', '.join(stale))
    print('PwaAssets.h and the page links are up to date')
else:
    header_path.write_text(header, encoding='utf-8')
    page_path.write_text(page, encoding='utf-8')
    print('src/PwaAssets.h: manifest and %d icons; webui.html links updated' % len(ICONS))
