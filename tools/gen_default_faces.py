"""Writes src/DefaultFaces.h: the standard watch faces (faces/modular.stheme,
faces/utility.stheme) as flash arrays. The firmware installs them on first
start, when no face is on the device, and selects Modular. Run after
rebuilding a face package; --check only compares."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FACES = [('modular', 'FACE_MODULAR'), ('utility', 'FACE_UTILITY')]
out_lines = ['// Generated by tools/gen_default_faces.py from faces/*.stheme. Do not edit.',
             '#pragma once', '#include <Arduino.h>', '']
for face, name in FACES:
    data = (ROOT / 'faces' / f'{face}.stheme').read_bytes()
    rows = [', '.join('0x%02x' % b for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    out_lines += [f'static const uint8_t {name}[] PROGMEM = {{', '  ' + ',\n  '.join(rows), '};', '']
out_lines += ['struct DefaultFace { const char* id; const uint8_t* data; size_t len; };',
              'static const DefaultFace DEFAULT_FACES[] = {',
              *[f'  {{"{face}", {name}, sizeof({name})}},' for face, name in FACES],
              '};', '']
text = '\n'.join(out_lines)
out = ROOT / 'src' / 'DefaultFaces.h'
if '--check' in sys.argv:
    ok = out.exists() and out.read_text(encoding='utf-8') == text
    print('DefaultFaces.h ' + ('matches' if ok else 'does not match') + ' faces/*.stheme')
    sys.exit(0 if ok else 1)
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write(text)
print('src/DefaultFaces.h: ' + ', '.join(f'{face} {(ROOT / "faces" / (face + ".stheme")).stat().st_size} B' for face, _ in FACES))
