#!/usr/bin/env python3
"""Generates src/features/theme/SystemFontData.h: the device's one system
font, SF Compact, in six text styles.

Usage: python tools/gen_system_font.py [FONT_FILE]
Default font: /System/Library/Fonts/SFCompact.ttf (macOS). Requires Pillow.

Every screen draws text in these styles: themes, notifications and the
firmware's own screens. Glyphs are cropped to their ink and stored at 2 bits
per pixel (four coverage levels), uncompressed, in flash.

Characters are display bytes (see displayText in ThemeEngine.h): printable
ASCII, Cyrillic at 0xC0-0xFF, Ё 0xA8, ё 0xB8 and the degree sign 0xB0. The
display styles only carry digits and a few signs; SystemFont.cpp draws any
other character in them from the headline style.
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else '/System/Library/Fonts/SFCompact.ttf'
OUT = Path(__file__).resolve().parent.parent / 'src/features/theme/SystemFontData.h'

FULL = [(c, chr(c)) for c in range(32, 127)]
FULL += [(0xC0 + i, chr(0x410 + i)) for i in range(64)]
FULL += [(0xA8, 'Ё'), (0xB8, 'ё'), (0xB0, '°')]
DIGITS = [(ord(c), c) for c in ' %+-.0123456789:'] + [(0xB0, '°')]

# name (as themes write it), size in px, variable-font style, characters
STYLES = [
    ('caption', 17, 'Regular', FULL),
    ('body', 22, 'Medium', FULL),
    ('headline', 28, 'Medium', FULL),
    ('display-s', 48, 'Medium', DIGITS),
    ('display-m', 70, 'Medium', DIGITS),
    ('display-l', 96, 'Semibold', DIGITS),
]


def style_data(size, style, chars):
    font = ImageFont.truetype(FONT, size)
    font.set_variation_by_name(style)
    baseline, line_height = round(size * 0.95), round(size * 1.22)
    codes, glyphs, bitmap = [], [], bytearray()
    for code, ch in sorted(chars):
        advance = max(1, round(font.getlength(ch)))
        left = top = width = height = 0
        offset = len(bitmap)
        if ch.strip():
            pad = size
            canvas = Image.new('L', (advance + 2 * pad, line_height + 2 * pad), 0)
            ImageDraw.Draw(canvas).text((pad, pad + baseline), ch, font=font, fill=255, anchor='ls')
            ink = canvas.getbbox()
            if ink:
                cell = canvas.crop(ink)
                left, top = ink[0] - pad, ink[1] - pad
                width, height = cell.size
                levels = [round(v * 3 / 255) for v in cell.getdata()]
                levels += [0] * (-len(levels) % 4)
                bitmap.extend((levels[i] << 6) | (levels[i + 1] << 4) | (levels[i + 2] << 2) | levels[i + 3]
                              for i in range(0, len(levels), 4))
        if not (-128 <= left < 128 and -128 <= top < 128 and advance < 256 and width < 256 and height < 256):
            raise ValueError(f'glyph {ch!r} at {size} px out of range')
        codes.append(code)
        glyphs.append((offset, advance, width, height, left, top))
    if len(bitmap) > 0xFFFF:
        raise ValueError(f'{size} px bitmap exceeds 64 KiB')
    return codes, glyphs, bytes(bitmap), baseline, line_height


def c_array(values, per_line=24):
    rows = [', '.join(str(v) for v in values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return '\n  ' + ',\n  '.join(rows) + '\n'


def main():
    out = [
        '// Generated by tools/gen_system_font.py from ' + Path(FONT).name + '. Do not edit.',
        '// The system font: six text styles, 2-bit glyphs cropped to their ink.',
        '// Included by SystemFont.cpp only.',
        '#pragma once',
        '',
        'namespace gm {',
        'namespace sysfontdata {',
        '// offset into the style bitmap; advance; ink width/height; ink position',
        '// relative to the pen (left) and to the top of the line (top).',
        'struct Glyph { uint16_t offset; uint8_t advance, width, height; int8_t left, top; };',
        'struct Style {',
        '  const uint8_t* codes;   // display bytes, ascending',
        '  const Glyph* glyphs;',
        '  const uint8_t* bitmap;  // row-major, four pixels per byte, high bits first',
        '  uint8_t count, size, baseline, lineHeight;',
        '  uint16_t bitmapSize;',
        '};',
    ]
    names, total = [], 0
    for index, (name, size, style, chars) in enumerate(STYLES):
        codes, glyphs, bitmap, baseline, line_height = style_data(size, style, chars)
        total += len(bitmap) + len(codes) * 9
        tag = f'S{index}'
        out.append(f'// {name}: {size} px {style}, {len(codes)} glyphs, {len(bitmap)} bytes of bitmap')
        out.append(f'static const uint8_t k{tag}Codes[{len(codes)}] PROGMEM = {{{c_array(codes)}}};')
        rows = ',\n  '.join(f'{{{o}, {a}, {w}, {h}, {l}, {t}}}' for o, a, w, h, l, t in glyphs)
        out.append(f'static const Glyph k{tag}Glyphs[{len(glyphs)}] PROGMEM = {{\n  {rows}\n}};')
        out.append(f'static const uint8_t k{tag}Bitmap[{max(1, len(bitmap))}] PROGMEM = {{{c_array(list(bitmap) or [0])}}};')
        names.append(f'{{k{tag}Codes, k{tag}Glyphs, k{tag}Bitmap, {len(codes)}, {size}, {baseline}, {line_height}, {len(bitmap)}}}')
    out.append('// In TextStyle order: ' + ', '.join(s[0] for s in STYLES) + '.')
    out.append('static const Style kStyles[' + str(len(STYLES)) + '] = {\n  ' + ',\n  '.join(names) + '\n};')
    out.append('}  // namespace sysfontdata')
    out.append('}  // namespace gm')
    OUT.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{OUT}: about {total} bytes of flash')


if __name__ == '__main__':
    main()
